std::uint32_t Instruction::rflags_read() const noexcept {
	return internal::FLAGS_READ[static_cast<std::size_t>(get_rflags_info(*this))];
}

std::uint32_t Instruction::rflags_written() const noexcept {
	return internal::FLAGS_WRITTEN[static_cast<std::size_t>(get_rflags_info(*this))];
}

std::uint32_t Instruction::rflags_cleared() const noexcept {
	return internal::FLAGS_CLEARED[static_cast<std::size_t>(get_rflags_info(*this))];
}

std::uint32_t Instruction::rflags_set() const noexcept {
	return internal::FLAGS_SET[static_cast<std::size_t>(get_rflags_info(*this))];
}

std::uint32_t Instruction::rflags_undefined() const noexcept {
	return internal::FLAGS_UNDEFINED[static_cast<std::size_t>(get_rflags_info(*this))];
}

std::uint32_t Instruction::rflags_modified() const noexcept {
	return internal::FLAGS_MODIFIED[static_cast<std::size_t>(get_rflags_info(*this))];
}

