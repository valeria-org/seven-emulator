	case Code::Uiret:
		return 24;
	case Code::Popad:
		return 32;
	case Code::Iretq:
		return 40;
	case Code::Eretu:
	case Code::Erets:
		return 48;
	case Code::Enterw_imm16_imm8:
		return -(2 + (static_cast<std::int32_t>(immediate8_2nd()) & 0x1F) * 2 + static_cast<std::int32_t>(immediate16()));
	case Code::Enterd_imm16_imm8:
		return -(4 + (static_cast<std::int32_t>(immediate8_2nd()) & 0x1F) * 4 + static_cast<std::int32_t>(immediate16()));
	case Code::Enterq_imm16_imm8:
		return -(8 + (static_cast<std::int32_t>(immediate8_2nd()) & 0x1F) * 8 + static_cast<std::int32_t>(immediate16()));
