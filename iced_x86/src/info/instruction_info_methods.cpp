RflagsInfo get_rflags_info(const Instruction& instruction) noexcept {
	const std::uint32_t flags1 = internal::INFO_TABLE[static_cast<std::size_t>(instruction.code())].flags1;
	const std::uint32_t implied_access = (flags1 >> InfoFlags1::IMPLIED_ACCESS_SHIFT) & InfoFlags1::IMPLIED_ACCESS_MASK;
	static_assert(static_cast<std::uint32_t>(ImpliedAccess::Shift_Ib_MASK1FMOD9) + 1 == static_cast<std::uint32_t>(ImpliedAccess::Shift_Ib_MASK1FMOD11), "");
	static_assert(static_cast<std::uint32_t>(ImpliedAccess::Shift_Ib_MASK1FMOD9) + 2 == static_cast<std::uint32_t>(ImpliedAccess::Shift_Ib_MASK1F), "");
	static_assert(static_cast<std::uint32_t>(ImpliedAccess::Shift_Ib_MASK1FMOD9) + 3 == static_cast<std::uint32_t>(ImpliedAccess::Shift_Ib_MASK3F), "");
	static_assert(static_cast<std::uint32_t>(ImpliedAccess::Shift_Ib_MASK1FMOD9) + 4 == static_cast<std::uint32_t>(ImpliedAccess::Clear_rflags), "");
	const RflagsInfo result = static_cast<RflagsInfo>((flags1 >> InfoFlags1::RFLAGS_INFO_SHIFT) & InfoFlags1::RFLAGS_INFO_MASK);
	const std::uint32_t e = implied_access - static_cast<std::uint32_t>(ImpliedAccess::Shift_Ib_MASK1FMOD9);
	switch (e) {
	case 0:
	case 1: {
		const std::uint32_t m = e == 0 ? 9 : 17;
		switch ((static_cast<std::uint32_t>(instruction.immediate8()) & 0x1F) % m) {
		case 0:
			return RflagsInfo::None;
		case 1:
			return RflagsInfo::R_c_W_co;
		default:
			break;
		}
		break;
	}

	case 2:
	case 3: {
		const std::uint32_t mask = e == 2 ? 0x1F : 0x3F;
		switch (static_cast<std::uint32_t>(instruction.immediate8()) & mask) {
		case 0:
			return RflagsInfo::None;
		case 1:
			if (result == RflagsInfo::W_c_U_o)
				return RflagsInfo::W_co;
			else if (result == RflagsInfo::R_c_W_c_U_o)
				return RflagsInfo::R_c_W_co;
			else {
				ICED_DEBUG_ASSERT(result == RflagsInfo::W_cpsz_U_ao);
				return RflagsInfo::W_copsz_U_a;
			}
		default:
			break;
		}
		break;
	}

	case 4:
		if (instruction.op0_register() == instruction.op1_register() && instruction.op0_kind() == OpKind::Register &&
			instruction.op1_kind() == OpKind::Register) {
			if (instruction.mnemonic() == Mnemonic::Xor)
				return RflagsInfo::C_cos_S_pz_U_a;
			else
				return RflagsInfo::C_acos_S_pz;
		}
		break;

	default:
		break;
	}
	return result;
}

