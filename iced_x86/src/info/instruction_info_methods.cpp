	case Code::Push_r64:
	case Code::Pushq_imm32:
	case Code::Pushq_imm8:
	case Code::Call_ptr1632:
	case Code::Pushfq:
	case Code::Call_rel32_64:
	case Code::Call_rm64:
	case Code::Call_m1632:
	case Code::Push_rm64:
