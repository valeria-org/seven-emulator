	case Code::Pushfd:
	case Code::Call_rel32_32:
	case Code::Call_rm32:
	case Code::Call_m1616:
	case Code::Push_rm32:
	case Code::Pushd_FS:
	case Code::Pushd_GS:
		return -4;
	case Code::Pushw_ES:
	case Code::Pushw_CS:
	case Code::Pushw_SS:
	case Code::Pushw_DS:
	case Code::Push_r16:
	case Code::Push_imm16:
