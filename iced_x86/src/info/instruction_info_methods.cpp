	case Code::Pop_r64:
	case Code::Pop_rm64:
	case Code::Popfq:
	case Code::Retnq:
	case Code::Retfd:
	case Code::Popq_FS:
	case Code::Popq_GS:
		return 8;
	case Code::Popaw:
	case Code::Retfq:
