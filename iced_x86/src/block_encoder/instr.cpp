std::uint32_t BlockEncInt::get_instruction_size(const Instruction& instruction, std::uint64_t ip) {
	EncoderInternal::clear_buffer(null_encoder);
	auto result = null_encoder.encode(instruction, ip);
	if (result.is_err())
		return static_cast<std::uint32_t>(IcedConstants::MAX_INSTRUCTION_LENGTH);
	return static_cast<std::uint32_t>(result.value());
}

std::int64_t correct_diff(bool in_block, std::int64_t diff, std::uint64_t gained) noexcept {
	if (in_block && diff >= 0) {
		ICED_DEBUG_ASSERT(static_cast<std::uint64_t>(diff) >= gained);
		return diff - static_cast<std::int64_t>(gained);
	}
	return diff;
}

std::pair<TargetInstr*, std::uint64_t> Instr::get_target_instr() noexcept {
	switch (type) {
	case InstrType::SimpleBranch:
	case InstrType::Jmp:
	case InstrType::Jcc:
	case InstrType::Call:
	case InstrType::Xbegin:
		return {&target_instr, instruction.near_branch_target()};
	case InstrType::IpRelMemOp:
		return {&target_instr, instruction.ip_rel_memory_address()};
	case InstrType::Simple:
	default:
		// Never called since base.done == true
		ICED_UNREACHABLE();
	}
}

bool Instr::optimize(InstrBase& base, InstrContext& ctx, std::uint64_t gained) {
	switch (type) {
	case InstrType::Simple:
		return false;
	case InstrType::SimpleBranch:
		return SimpleBranchInstr::optimize(*this, base, ctx, gained);
	case InstrType::Jmp:
		return JmpInstr::optimize(*this, base, ctx, gained);
	case InstrType::Jcc:
		return JccInstr::optimize(*this, base, ctx, gained);
	case InstrType::Call:
		return CallInstr::optimize(*this, base, ctx, gained);
	case InstrType::IpRelMemOp:
		return IpRelMemOpInstr::optimize(*this, base, ctx, gained);
	case InstrType::Xbegin:
		return XbeginInstr::optimize(*this, base, ctx, gained);
	default:
		ICED_UNREACHABLE();
	}
}

Result<InstrEncodeResult> Instr::encode(InstrBase& base, InstrContext& ctx) {
	switch (type) {
	case InstrType::Simple:
		return SimpleInstr::encode(*this, base, ctx);
	case InstrType::SimpleBranch:
		return SimpleBranchInstr::encode(*this, base, ctx);
	case InstrType::Jmp:
		return JmpInstr::encode(*this, base, ctx);
	case InstrType::Jcc:
		return JccInstr::encode(*this, base, ctx);
	case InstrType::Call:
		return CallInstr::encode(*this, base, ctx);
	case InstrType::IpRelMemOp:
		return IpRelMemOpInstr::encode(*this, base, ctx);
	case InstrType::Xbegin:
		return XbeginInstr::encode(*this, base, ctx);
	default:
		ICED_UNREACHABLE();
	}
}

IcedError InstrUtils::create_error_message(const char* error_message, const Instruction& instruction) {
	// "{error_message} : 0x{ip:X}"
	static const char HEX_DIGITS[] = "0123456789ABCDEF";
	char hex[16];
	std::size_t hex_len = 0;
	std::uint64_t ip = instruction.ip();
	do {
		hex[hex_len++] = HEX_DIGITS[ip & 0xF];
		ip >>= 4;
	} while (ip != 0);

	std::string message(error_message);
	message.append(" : 0x");
	while (hex_len > 0)
		message.push_back(hex[--hex_len]);
	return IcedError(std::move(message));
}

