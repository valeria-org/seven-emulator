Result<std::uint32_t> InstrUtils::encode_branch_to_pointer_data(Block& block, bool is_call, std::uint64_t ip, std::uint32_t pointer_data,
	std::uint32_t min_size) {
	if (min_size > static_cast<std::uint32_t>(INT32_MAX))
		return IcedError("Internal error");

	Instruction instr;
	instr.set_op0_kind(OpKind::Memory);
	instr.set_memory_displ_size(block.encoder.bitness() / 8);
	RelocKind reloc_kind;
	switch (block.encoder.bitness()) {
	case 64: {
		instr.set_code(is_call ? Code::Call_rm64 : Code::Jmp_rm64);
		instr.set_memory_base(Register::RIP);

		auto target_addr_result = block.data(pointer_data).address();
		if (target_addr_result.is_err())
			return target_addr_result.error();
		const std::uint64_t target_addr = target_addr_result.value();
		const std::uint64_t next_rip = ip + CALL_OR_JMP_POINTER_DATA_INSTRUCTION_SIZE64;
		const auto diff = static_cast<std::int64_t>(target_addr - next_rip);
		if (!(INT32_MIN <= diff && diff <= INT32_MAX))
			return IcedError("Block is too big");

		instr.set_memory_displacement64(target_addr);
		reloc_kind = RelocKind::Offset64;
		break;
	}

	default:
		ICED_UNREACHABLE();
	}

	auto encode_result = block.encoder.encode(instr, ip);
	if (encode_result.is_err())
		return encode_result.error();
	auto size = static_cast<std::uint32_t>(encode_result.value());
	if (block.can_add_reloc_infos() && reloc_kind != RelocKind::Offset64) {
		auto co = block.encoder.get_constant_offsets();
		if (!co.has_displacement())
			return IcedError("Internal error");
		block.add_reloc_info(RelocInfo(reloc_kind, ip + co.displacement_offset()));
	}
	while (size < min_size) {
		size++;
		block.write_byte(0x90);
	}
	return size;
}

